def match_topic(filename):
    for pattern, rule in TOPIC_RULES:
        if re.search(pattern, filename, re.IGNORECASE):
            return rule
    return DEFAULT_RULE

def extract_magnification(filename):
    m = re.search(r'[-_.]?(х|x|X)?(\d+)(\.\d+)?\.?(jpg|jpeg|png)$', filename, re.IGNORECASE)
    if m:
        num = m.group(2)
        return f"х{num}"
    return ""

